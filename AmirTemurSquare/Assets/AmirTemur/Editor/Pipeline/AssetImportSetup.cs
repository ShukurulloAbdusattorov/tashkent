        static bool BuildPrefab(string key, string model, string fbx, StringBuilder log)
        {
            var modelAsset = AssetDatabase.LoadAssetAtPath<GameObject>(fbx);
            if (modelAsset == null) return false;
            if (!Targets.TryGetValue(key, out var target)) target = new Target { size = 0f };

            MeshUtil.EnsureFolder(PrefabLibrary.Folder);
            string prefabPath = $"{PrefabLibrary.Folder}/{key}.prefab";

            var root = new GameObject(key);
            try
            {
                var inst = (GameObject)PrefabUtility.InstantiatePrefab(modelAsset);
                inst.name = model;
                inst.transform.SetParent(root.transform, false);
                // keep the importer's root rotation/scale (FBX axis fix-up + unit scale); only the position is normalised
                inst.transform.localPosition = Vector3.zero;
                var importRot = inst.transform.localRotation; var importScale = inst.transform.localScale;

                SelectVariant(inst, key, target, log);

                var renderers = inst.GetComponentsInChildren<Renderer>(false);
                foreach (var r in renderers)
                {
                    r.shadowCastingMode = ShadowCastingMode.On;
                    r.receiveShadows = true;
                    r.motionVectorGenerationMode = MotionVectorGenerationMode.Camera;
                }

                Bounds b = ComputeBounds(renderers, out bool ok);
                if (ok)
                {
                    float measure = target.horizontal ? Mathf.Max(b.size.x, b.size.z) : b.size.y;
                    if (measure > 1e-4f && target.size > 0f)
                    {
                        float ratio = target.size / measure;
                        if (ratio > ScaleTolerance || ratio < 1f / ScaleTolerance)
                        {
                            inst.transform.localScale = importScale * ratio;
                            log.AppendLine($"  {key}: measured {measure:F2} m, target {target.size:F2} m -> scale x{ratio:F3}");
                            b = ComputeBounds(renderers, out ok);
                        }
                    }
                    // pivot at ground level, centred in XZ
                    inst.transform.localPosition = new Vector3(-b.center.x, -b.min.y, -b.center.z);
                    b = ComputeBounds(renderers, out ok);
                }

                foreach (var t in root.GetComponentsInChildren<Transform>(true))
                    GameObjectUtility.SetStaticEditorFlags(t.gameObject, PropStaticFlags);

                long tris = CountTriangles(renderers);
                bool meshLod = HasMeshLod(renderers);
                if (tris > LodGroupTriangleThreshold && !meshLod)
                {
                    var lg = root.AddComponent<LODGroup>();
                    lg.fadeMode = LODFadeMode.None;
                    lg.SetLODs(new[] { new LOD(LodCullScreenHeight, renderers) });
                    lg.RecalculateBounds();
                }

                if (key.StartsWith("lamp", StringComparison.OrdinalIgnoreCase))
                {
                    var anchor = new GameObject("LampHeadAnchor");
                    anchor.transform.SetParent(root.transform, false);
                    anchor.transform.position = FindLampHead(renderers, b);
                }

                var saved = PrefabUtility.SaveAsPrefabAsset(root, prefabPath);
                log.AppendLine($"  prefab {prefabPath}: size {b.size.x:F2}x{b.size.y:F2}x{b.size.z:F2} m, {tris} tris, meshLod={meshLod}, renderers={renderers.Length}");
                return saved != null;
            }
            finally
            {
                Object.DestroyImmediate(root);
            }
        }

        /// <summary>Poly Haven packs several variants side by side in one FBX (shrub a-d, fresh/aged hydrant, two trash cans, a seating kit).
        /// Keep one variant: explicit child list when configured, else cluster every child around the "major" objects and keep the
        /// preferred / largest cluster. Overlapping majors (car body + wheels, manhole frame + cover) are treated as one assembly.</summary>
        static void SelectVariant(GameObject inst, string key, Target target, StringBuilder log)
        {
            var children = new List<Transform>();
            foreach (Transform c in inst.transform)
                if (c.GetComponentInChildren<Renderer>(true) != null) children.Add(c);
            if (children.Count < 2) return;

            if (target.keepChildren != null && target.keepChildren.Length > 0)
            {
                int kept = 0;
                foreach (var c in children)
                {
                    bool keep = target.keepChildren.Any(k => c.name.IndexOf(k, StringComparison.OrdinalIgnoreCase) >= 0);
                    c.gameObject.SetActive(keep);
                    if (keep) kept++;
                }
                if (kept == 0) foreach (var c in children) c.gameObject.SetActive(true);
                log.AppendLine($"  {key}: kept {kept}/{children.Count} children by name");
                return;
            }

            var infos = children.Select(c => (t: c, b: ComputeBounds(c.GetComponentsInChildren<Renderer>(true), out _))).ToList();
            float maxVol = infos.Max(i => Volume(i.b));
            if (maxVol <= 0f) return;
            var majors = infos.Where(i => Volume(i.b) >= 0.3f * maxVol).ToList();
            if (majors.Count < 2) return;
            var largest = majors.OrderByDescending(i => Volume(i.b)).First();
            if (!majors.Any(mj => mj.t != largest.t && !OverlapsXZ(mj.b, largest.b, 0.02f))) return; // one assembly

            var clusters = majors.ToDictionary(mj => mj.t, mj => new List<(Transform t, Bounds b)> { (mj.t, mj.b) });
            foreach (var i in infos)
            {
                if (clusters.ContainsKey(i.t)) continue;
                var nearest = majors.OrderBy(mj => DistXZ(mj.b.center, i.b.center)).First();
                clusters[nearest.t].Add(i);
            }

            Transform chosen = null;
            if (!string.IsNullOrEmpty(target.preferChild))
                chosen = clusters.Keys.FirstOrDefault(k => clusters[k].Any(e => e.t.name.IndexOf(target.preferChild, StringComparison.OrdinalIgnoreCase) >= 0));
            chosen ??= clusters.OrderByDescending(kv => kv.Value.Sum(e => Volume(e.b))).First().Key;

            int disabled = 0;
            foreach (var kv in clusters)
            {
                if (kv.Key == chosen) continue;
                foreach (var e in kv.Value) { e.t.gameObject.SetActive(false); disabled++; }
            }
            log.AppendLine($"  {key}: {clusters.Count} packed variants, kept cluster '{chosen.name}', disabled {disabled} object(s)");
        }

        static float Volume(Bounds b) => Mathf.Max(b.size.x, 1e-3f) * Mathf.Max(b.size.y, 1e-3f) * Mathf.Max(b.size.z, 1e-3f);
        static float DistXZ(Vector3 a, Vector3 b) => Vector2.Distance(new Vector2(a.x, a.z), new Vector2(b.x, b.z));
        static bool OverlapsXZ(Bounds a, Bounds b, float pad) =>
            a.min.x - pad <= b.max.x && b.min.x - pad <= a.max.x && a.min.z - pad <= b.max.z && b.min.z - pad <= a.max.z;

        static Mesh MeshOf(Renderer r)
        {
            if (r is SkinnedMeshRenderer smr) return smr.sharedMesh;
            var mf = r.GetComponent<MeshFilter>();
            return mf != null ? mf.sharedMesh : null;
        }

        /// <summary>World-space bounds from mesh bounds x renderer matrices (independent of renderer activity/culling state).</summary>
        static Bounds ComputeBounds(IEnumerable<Renderer> renderers, out bool ok)
        {
            ok = false;
            var b = new Bounds();
            foreach (var r in renderers)
            {
                var mesh = MeshOf(r);
                if (mesh == null) continue;
                var lb = mesh.bounds;
                var m = r.transform.localToWorldMatrix;
                for (int i = 0; i < 8; i++)
                {
                    var corner = new Vector3((i & 1) == 0 ? lb.min.x : lb.max.x, (i & 2) == 0 ? lb.min.y : lb.max.y, (i & 4) == 0 ? lb.min.z : lb.max.z);
                    var p = m.MultiplyPoint3x4(corner);
                    if (!ok) { b = new Bounds(p, Vector3.zero); ok = true; }
                    else b.Encapsulate(p);
                }
            }
            return b;
        }

        static long CountTriangles(IEnumerable<Renderer> renderers)
        {
            long n = 0;
            foreach (var r in renderers)
            {
                var mesh = MeshOf(r);
                if (mesh == null) continue;
                for (int s = 0; s < mesh.subMeshCount; s++) n += mesh.GetIndexCount(s) / 3;
            }
            return n;
        }

        static bool HasMeshLod(IEnumerable<Renderer> renderers)
        {
#if UNITY_6000_2_OR_NEWER
            foreach (var r in renderers)
            {
                var mesh = MeshOf(r);
                if (mesh != null && mesh.lodCount > 1) return true;
            }
#endif
            return false;
        }

        /// <summary>Centroid of the vertices in the top 12% of the lamp; falls back to the top centre of the bounds.</summary>
        static Vector3 FindLampHead(IEnumerable<Renderer> renderers, Bounds b)
        {
            try
            {
                float yMin = b.max.y - 0.12f * b.size.y;
                Vector3 sum = Vector3.zero; int n = 0;
                foreach (var r in renderers)
                {
                    var mesh = MeshOf(r);
                    if (mesh == null || (!mesh.isReadable && Application.isPlaying)) continue;
                    var m = r.transform.localToWorldMatrix;
                    foreach (var v in mesh.vertices)
                    {
                        var p = m.MultiplyPoint3x4(v);
                        if (p.y >= yMin) { sum += p; n++; }
                    }
                }
                if (n > 0) return sum / n;
            }
            catch (Exception) { /* non-readable mesh: fall back */ }
            return new Vector3(b.center.x, b.max.y, b.center.z);
        }

