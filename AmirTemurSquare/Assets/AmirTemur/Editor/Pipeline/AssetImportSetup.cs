        /// <summary>Re-applies TextureImportPostprocessor rules to assets already imported before the postprocessor existed.</summary>
        static int EnsureImportSettings(StringBuilder log)
        {
            int count = 0;
            foreach (string guid in AssetDatabase.FindAssets("t:Texture", new[] { ArtFolder }))
            {
                string path = AssetDatabase.GUIDToAssetPath(guid);
                if (!TextureImportPostprocessor.Owns(path)) continue;
                if (AssetImporter.GetAtPath(path) is not TextureImporter ti) continue;
                if (TextureImportPostprocessor.ApplyTexture(ti, path)) { ti.SaveAndReimport(); count++; }
            }
            foreach (string guid in AssetDatabase.FindAssets("t:GameObject", new[] { ModelsFolder }))
            {
                string path = AssetDatabase.GUIDToAssetPath(guid);
                if (!TextureImportPostprocessor.IsModelPath(path)) continue;
                if (AssetImporter.GetAtPath(path) is not ModelImporter mi) continue;
                if (TextureImportPostprocessor.ApplyModel(mi, path)) { mi.SaveAndReimport(); count++; log.AppendLine($"  model importer updated: {path}"); }
            }
            return count;
        }

