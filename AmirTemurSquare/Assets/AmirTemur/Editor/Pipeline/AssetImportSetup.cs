        static void CopyCityJson(StringBuilder log)
        {
            string dst = CityData.DefaultPath;
            string full = Path.Combine(Directory.GetCurrentDirectory(), dst);
            if (File.Exists(full)) { log.AppendLine($"[AssetImportSetup] {dst} present"); return; }
            if (!File.Exists(CityJsonSource)) { Debug.LogWarning($"[AssetImportSetup] city.json source missing: {CityJsonSource}"); return; }
            MeshUtil.EnsureFolder(DataFolder);
            File.Copy(CityJsonSource, full);
            AssetDatabase.ImportAsset(dst);
            log.AppendLine($"[AssetImportSetup] copied city.json -> {dst}");
        }
