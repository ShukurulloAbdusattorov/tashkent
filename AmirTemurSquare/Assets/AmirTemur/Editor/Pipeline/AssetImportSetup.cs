        static Dictionary<string, TexGroup> CollectTextureGroups(string texDir)
        {
            var groups = new Dictionary<string, TexGroup>(StringComparer.OrdinalIgnoreCase);
            string full = Path.Combine(Directory.GetCurrentDirectory(), texDir);
            if (!Directory.Exists(full)) return groups;

            TexGroup Get(string prefix)
            {
                if (!groups.TryGetValue(prefix, out var g)) { g = new TexGroup { prefix = prefix, dir = texDir }; groups[prefix] = g; }
                return g;
            }

            foreach (string file in Directory.GetFiles(full))
            {
                string name = Path.GetFileName(file);
                if (name.EndsWith(".meta", StringComparison.OrdinalIgnoreCase)) continue;
                string assetPath = $"{texDir}/{name}";

                var gm = GenRx.Match(name);
                if (gm.Success)
                {
                    var g = Get(gm.Groups["prefix"].Value);
                    if (gm.Groups["kind"].Value.Equals("Mask", StringComparison.OrdinalIgnoreCase)) g.mask = assetPath; else g.baseA = assetPath;
                    continue;
                }
                var m = RawRx.Match(name);
                if (!m.Success) continue;
                var grp = Get(m.Groups["prefix"].Value);
                switch (m.Groups["kind"].Value.ToLowerInvariant())
                {
                    case "diff": case "diffuse": grp.diff ??= assetPath; break;
                    case "nor_gl": grp.nor ??= assetPath; break;
                    case "nor_dx": grp.norDx ??= assetPath; break;
                    case "arm": grp.arm ??= assetPath; break;
                    case "rough": grp.rough ??= assetPath; break;
                    case "ao": grp.ao ??= assetPath; break;
                    case "metal": grp.metal ??= assetPath; break;
                    case "alpha": grp.alpha ??= assetPath; break;
                    case "mask": grp.rawMask ??= assetPath; break;
                    case "disp": grp.disp ??= assetPath; break;
                    case "opacity": grp.opacity ??= assetPath; break;
                }
            }
            return groups;
        }

        /// <summary>process_assets.py fails on EXR sources (PIL); build the missing HDRP mask / alpha base colour on the GPU here.</summary>
        static void EnsureGeneratedTextures(TexGroup g, StringBuilder log)
        {
            if (g.mask == null && (g.rough != null || g.arm != null))
            {
                string outPath = $"{g.dir}/{g.prefix}_Mask.png";
                try { if (GenerateMask(g, outPath)) { g.mask = outPath; log.AppendLine($"  generated {outPath}"); } }
                catch (Exception e) { Debug.LogWarning($"[AssetImportSetup] mask generation failed for {g.prefix}: {e.Message}"); }
            }
            if (g.baseA == null && g.diff != null && g.AlphaSource != null)
            {
                string outPath = $"{g.dir}/{g.prefix}_BaseColorA.png";
                try { if (GenerateBaseColorA(g.diff, g.AlphaSource, outPath)) { g.baseA = outPath; log.AppendLine($"  generated {outPath}"); } }
                catch (Exception e) { Debug.LogWarning($"[AssetImportSetup] base colour alpha generation failed for {g.prefix}: {e.Message}"); }
            }
        }

        static Texture2D Load(string path) => string.IsNullOrEmpty(path) ? null : AssetDatabase.LoadAssetAtPath<Texture2D>(path);

        /// <summary>GPU read-back of any imported texture (works without Read/Write enabled). sRGB=true keeps sRGB-encoded bytes.</summary>
        static Color32[] ReadPixels(Texture2D src, int w, int h, bool srgb)
        {
            var rt = RenderTexture.GetTemporary(w, h, 0, RenderTextureFormat.ARGB32, srgb ? RenderTextureReadWrite.sRGB : RenderTextureReadWrite.Linear);
            var prev = RenderTexture.active;
            Texture2D tmp = null;
            try
            {
                Graphics.Blit(src, rt);
                RenderTexture.active = rt;
                tmp = new Texture2D(w, h, TextureFormat.RGBA32, false, !srgb);
                tmp.ReadPixels(new Rect(0, 0, w, h), 0, 0);
                tmp.Apply(false);
                return tmp.GetPixels32();
            }
            finally
            {
                RenderTexture.active = prev;
                RenderTexture.ReleaseTemporary(rt);
                if (tmp != null) Object.DestroyImmediate(tmp);
            }
        }

        static void WritePng(Color32[] px, int w, int h, string assetPath)
        {
            var tex = new Texture2D(w, h, TextureFormat.RGBA32, false);
            try
            {
                tex.SetPixels32(px);
                tex.Apply(false);
                string full = Path.Combine(Directory.GetCurrentDirectory(), assetPath);
                File.WriteAllBytes(full, tex.EncodeToPNG());
            }
            finally { Object.DestroyImmediate(tex); }
            AssetDatabase.ImportAsset(assetPath, ImportAssetOptions.ForceSynchronousImport);
        }

        static bool GenerateMask(TexGroup g, string outPath)
        {
            Texture2D rough = Load(g.rough), metal = Load(g.metal), ao = Load(g.ao), arm = Load(g.arm);
            Texture2D size = rough ?? arm;
            if (size == null) return false;
            int w = Mathf.Min(size.width, 2048), h = Mathf.Min(size.height, 2048);
            Color32[] armPx = arm != null ? ReadPixels(arm, w, h, false) : null;
            Color32[] roughPx = arm == null && rough != null ? ReadPixels(rough, w, h, false) : null;
            Color32[] metalPx = arm == null && metal != null ? ReadPixels(metal, w, h, false) : null;
            Color32[] aoPx = arm == null && ao != null ? ReadPixels(ao, w, h, false) : null;
            if (armPx == null && roughPx == null) return false;

            var outPx = new Color32[w * h];
            for (int i = 0; i < outPx.Length; i++)
            {
                byte metalV = armPx != null ? armPx[i].b : metalPx != null ? metalPx[i].r : (byte)0;
                byte aoV = armPx != null ? armPx[i].r : aoPx != null ? aoPx[i].r : (byte)255;
                byte roughV = armPx != null ? armPx[i].g : roughPx[i].r;
                outPx[i] = new Color32(metalV, aoV, 0, (byte)(255 - roughV));
            }
            WritePng(outPx, w, h, outPath);
            return true;
        }

        static bool GenerateBaseColorA(string diffPath, string alphaPath, string outPath)
        {
            Texture2D diff = Load(diffPath), alpha = Load(alphaPath);
            if (diff == null || alpha == null) return false;
            int w = Mathf.Min(diff.width, 2048), h = Mathf.Min(diff.height, 2048);
            var rgb = ReadPixels(diff, w, h, true);
            var a = ReadPixels(alpha, w, h, false);
            for (int i = 0; i < rgb.Length; i++) rgb[i].a = a[i].r;
            WritePng(rgb, w, h, outPath);
            return true;
        }

