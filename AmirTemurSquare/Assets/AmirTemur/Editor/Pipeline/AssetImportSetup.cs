        static int BuildModelMaterials(string model, string fbx, StringBuilder log)
        {
            string texDir = $"{ModelsFolder}/{model}/textures";
            var groups = CollectTextureGroups(texDir);
            foreach (var g in groups.Values) EnsureGeneratedTextures(g, log);

            if (AssetImporter.GetAtPath(fbx) is not ModelImporter importer) return 0;

            // FBX sub-material names: embedded materials (first import) + already remapped source names (subsequent runs)
            var names = AssetDatabase.LoadAllAssetsAtPath(fbx).OfType<Material>().Select(m => m.name).Distinct().ToList();
            foreach (var kv in importer.GetExternalObjectMap())
                if (kv.Key.type == typeof(Material) && !names.Contains(kv.Key.name)) names.Add(kv.Key.name);
            if (names.Count == 0)
            {
                var go = AssetDatabase.LoadAssetAtPath<GameObject>(fbx);
                if (go != null)
                    foreach (var r in go.GetComponentsInChildren<Renderer>(true))
                        foreach (var m in r.sharedMaterials)
                            if (m != null && !names.Contains(m.name)) names.Add(m.name);
            }
            if (names.Count == 0) names.Add(model);

            MeshUtil.EnsureFolder(ModelMaterialsFolder);
            int count = 0;
            bool remapChanged = false;
            var existingMap = importer.GetExternalObjectMap();
            foreach (string matName in names)
            {
                string prefix = MatchPrefix(matName, groups.Keys, model);
                TexGroup g = prefix != null ? groups[prefix] : null;
                string part = matName.Equals(model, StringComparison.OrdinalIgnoreCase) ? "main"
                            : matName.StartsWith(model + "_", StringComparison.OrdinalIgnoreCase) ? matName.Substring(model.Length + 1)
                            : matName;
                foreach (char c in Path.GetInvalidFileNameChars()) part = part.Replace(c, '_');
                string path = $"{ModelMaterialsFolder}/{model}_{part}.mat";

                var mat = AssetDatabase.LoadAssetAtPath<Material>(path);
                if (mat == null)
                {
                    mat = new Material(Shader.Find("HDRP/Lit")) { name = $"{model}_{part}" };
                    AssetDatabase.CreateAsset(mat, path);
                }
                ConfigureModelMaterial(mat, matName, g, model);
                var ident = new AssetImporter.SourceAssetIdentifier(typeof(Material), matName);
                if (!existingMap.TryGetValue(ident, out var already) || already != mat)
                {
                    importer.AddRemap(ident, mat);
                    remapChanged = true;
                }
                log.AppendLine($"  {model}: material '{matName}' -> {path} (textures: {(g != null ? g.prefix : "none")})");
                count++;
            }
            // re-importing a multi-million-triangle tree costs minutes and gigabytes (it crashed an 8 GB machine), so only do it when a remap actually changed
            if (remapChanged) importer.SaveAndReimport();
            else log.AppendLine($"  {model}: remaps unchanged, no reimport");
            return count;
        }

        /// <summary>Case-insensitive match of an FBX material name to a texture prefix: exact, else longest substring either way,
        /// else the prefix equal to the model name, else the first prefix.</summary>
        static string MatchPrefix(string matName, IEnumerable<string> prefixes, string model)
        {
            string n = matName.ToLowerInvariant();
            string best = null; int bestLen = -1;
            foreach (string p in prefixes)
            {
                string pl = p.ToLowerInvariant();
                if (pl == n) return p;
                if ((n.Contains(pl) || pl.Contains(n)) && pl.Length > bestLen) { best = p; bestLen = pl.Length; }
            }
            if (best != null) return best;
            foreach (string p in prefixes) if (p.Equals(model, StringComparison.OrdinalIgnoreCase)) return p;
            return prefixes.FirstOrDefault();
        }

        static void ConfigureModelMaterial(Material m, string matName, TexGroup g, string model)
        {
            string lower = matName.ToLowerInvariant();
            Texture2D baseTex = g != null ? (Load(g.baseA) ?? Load(g.diff)) : null;
            Texture2D normal = g != null ? Load(g.nor) : null;
            Texture2D mask = g != null ? Load(g.mask) : null;
            bool hasAlpha = g != null && g.baseA != null && baseTex != null && baseTex == Load(g.baseA);

            m.SetColor("_BaseColor", Color.white);
            m.SetTexture("_BaseColorMap", baseTex);
            m.SetTexture("_NormalMap", normal);
            m.SetFloat("_NormalScale", 1f);
            m.SetTexture("_MaskMap", mask);
            if (mask != null)
            {
                m.SetFloat("_Metallic", 1f); m.SetFloat("_Smoothness", 1f);
                m.SetFloat("_SmoothnessRemapMin", 0f); m.SetFloat("_SmoothnessRemapMax", 1f);
                m.SetFloat("_AORemapMin", 0f); m.SetFloat("_AORemapMax", 1f);
            }
            else
            {
                bool metallic = lower.Contains("metal") || lower.Contains("lamp") || lower.Contains("hydrant") || lower.Contains("manhole") || lower.Contains("statue");
                m.SetFloat("_Metallic", metallic ? 0.85f : 0f);
                m.SetFloat("_Smoothness", metallic ? 0.55f : lower.Contains("leaves") || lower.Contains("twigs") ? 0.25f : 0.35f);
            }

            if (hasAlpha)
            {
                HDMaterial.SetAlphaClipping(m, true);
                HDMaterial.SetAlphaCutoff(m, 0.5f);
                m.SetFloat("_DoubleSidedEnable", 1f);
                m.SetFloat("_DoubleSidedNormalMode", 1f); // mirror
            }
            else
            {
                HDMaterial.SetAlphaClipping(m, false);
                m.SetFloat("_DoubleSidedEnable", 0f);
            }

            if (lower.Contains("glass"))
            {
                HDMaterial.SetSurfaceType(m, true);
                m.SetFloat("_BlendMode", 0f);
                m.SetFloat("_EnableBlendModePreserveSpecularLighting", 1f);
                m.SetColor("_BaseColor", new Color(0.85f, 0.9f, 0.95f, 0.3f));
                m.SetTexture("_MaskMap", null);
                m.SetFloat("_Metallic", 0f); m.SetFloat("_Smoothness", 0.95f);
                m.renderQueue = (int)RenderQueue.Transparent;
            }
            else if (lower.Contains("bulb"))
            {
                var e = new Color(1f, 0.85f, 0.6f);
                m.SetFloat("_UseEmissiveIntensity", 1f);
                m.SetColor("_EmissiveColorLDR", e);
                m.SetFloat("_EmissiveIntensity", 800f);
                m.SetColor("_EmissiveColor", e * 800f);
                m.SetFloat("_EmissiveExposureWeight", 0.7f);
            }

            HDMaterial.ValidateMaterial(m);
            EditorUtility.SetDirty(m);
        }

