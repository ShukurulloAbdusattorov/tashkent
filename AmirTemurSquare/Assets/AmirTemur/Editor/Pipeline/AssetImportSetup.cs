        // <prefix>_<kind>_<res>.<ext> as produced by Poly Haven (copied verbatim by process_assets.py)
        static readonly Regex RawRx = new(@"^(?<prefix>.+?)_(?<kind>diff|diffuse|nor_gl|nor_dx|arm|rough|ao|metal|alpha|mask|disp|opacity|spec)_(?<res>\d+k)\.(?<ext>png|jpg|jpeg|exr|tga)$", RegexOptions.IgnoreCase);
        // generated by process_assets.py (or by this class)
        static readonly Regex GenRx = new(@"^(?<prefix>.+)_(?<kind>Mask|BaseColorA)\.png$", RegexOptions.IgnoreCase);

        class TexGroup
        {
            public string prefix, dir;
            public string diff, nor, norDx, arm, rough, ao, metal, alpha, rawMask, disp, opacity;
            public string mask, baseA; // generated
            public string AlphaSource => alpha ?? opacity ?? rawMask;
        }

        [MenuItem("AmirTemur/Asset Import Setup")]
        public static void Run()
        {
            var sw = Stopwatch.StartNew();
            var log = new StringBuilder();
            log.AppendLine("[AssetImportSetup] start");

            AssetDatabase.Refresh();

            int reimported = EnsureImportSettings(log);
            log.AppendLine($"[AssetImportSetup] importer settings re-checked, {reimported} asset(s) reimported");

            MaterialLibrary.RebuildAll();
            log.AppendLine($"[AssetImportSetup] MaterialLibrary rebuilt ({MaterialLibrary.Definitions.Count} definitions)");

            int materials = 0, prefabs = 0;
            var missing = new List<string>();
            foreach (var kv in PrefabLibrary.Sources)
            {
                string key = kv.Key, model = kv.Value;
                string fbx = $"{ModelsFolder}/{model}/{model}.fbx";
                if (AssetDatabase.LoadAssetAtPath<GameObject>(fbx) == null)
                {
                    missing.Add($"{key} ({fbx})");
                    continue;
                }
                try { materials += BuildModelMaterials(model, fbx, log); }
                catch (Exception e) { Debug.LogError($"[AssetImportSetup] materials for {model} failed: {e}"); }
                try { if (BuildPrefab(key, model, fbx, log)) prefabs++; }
                catch (Exception e) { Debug.LogError($"[AssetImportSetup] prefab for {key} failed: {e}"); }
            }

            CopyCityJson(log);

            AssetDatabase.SaveAssets();
            AssetDatabase.Refresh();

            log.AppendLine($"[AssetImportSetup] done in {sw.Elapsed.TotalSeconds:F1}s: {materials} model materials, {prefabs}/{PrefabLibrary.Sources.Count} prefabs" +
                           (missing.Count > 0 ? $", missing models: {string.Join(", ", missing)}" : ""));
            Debug.Log(log.ToString());
        }

